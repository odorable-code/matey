SELECT
CASE
    WHEN DATEDIFF(CURDATE(), DATE('2023-10-20')) = 0 THEN '오늘'
    WHEN DATEDIFF(CURDATE(), DATE('2023-10-19')) = 1 THEN '어제'
    WHEN DATEDIFF(CURDATE(), DATE('2023-10-15')) < 7 THEN CONCAT(DATEDIFF(CURDATE(), DATE('2023-10-15')), '일 전')
    ELSE CONCAT(FLOOR(DATEDIFF(CURDATE(), DATE('2023-10-01')) / 7), '주 전')
END as date
